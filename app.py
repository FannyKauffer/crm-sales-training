@app.route('/api/ask', methods=['POST'])
@api_login_required
def ask():
    if not os.environ.get('ANTHROPIC_API_KEY'):
        return jsonify({'error': 'ANTHROPIC_API_KEY not set'}), 500
    body = request.get_json(silent=True) or {}
    question = (body.get('question') or '').strip()[:2000]
    if not question:
        return jsonify({'error': 'Empty question'}), 400

    # Short conversation memory sent by the browser (last few turns)
    history = []
    for m in (body.get('history') or [])[-6:]:
        if m.get('role') in ('user', 'assistant') and isinstance(m.get('content'), str):
            history.append({'role': m['role'], 'content': m['content'][:4000]})
    if history and history[0]['role'] != 'user':
        history = history[1:]

    try:
        response = claude_client().beta.messages.create(
            model=CLAUDE_MODEL,
            max_tokens=4000,
            betas=['server-side-fallback-2026-07-01'],
            fallbacks='default',
            output_config={'effort': 'low'},
            system=[{'type': 'text', 'text': QA_SYSTEM, 'cache_control': {'type': 'ephemeral'}}],
            messages=history + [{'role': 'user', 'content': question}],
        )
    except anthropic.RateLimitError:
        return jsonify({'error': 'Too many questions right now, try again in a minute.'}), 429
    except anthropic.APIStatusError as e:
        return jsonify({'error': f'Claude API error ({e.status_code}): {e.message}'}), 502
    except anthropic.APIConnectionError:
        return jsonify({'error': 'Could not reach the Claude API.'}), 502

    if response.stop_reason == 'refusal':
        return jsonify({'answer': "I can't answer that one. Please ask Sales Ops directly."})
    answer = ''.join(b.text for b in response.content if b.type == 'text').strip()
    return jsonify({'answer': answer})


